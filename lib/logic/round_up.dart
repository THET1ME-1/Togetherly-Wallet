import '../data/models.dart';

/// Округление покупки в копилку.
///
/// Приём из второй статьи: банк округляет списание вверх и разницу кладёт в
/// накопления. Здесь это делает приложение, но честно — отдельным переводом,
/// который видно в истории. Тихое «куда-то ушло 7,40» в трекере денег хуже,
/// чем отсутствие приёма.

/// Сколько добавить к трате [amount], чтобы она стала кратной [step].
///
/// Шаг задаётся в единицах валюты (10, 50, 100). Ровная сумма не округляется:
/// перевод на нуль ничего не значит, а строку в истории добавил бы.
double roundUpFor(double amount, int step) {
  if (step <= 0) return 0;
  final minor = (amount.abs() * 100).round();
  final unit = step * 100;
  final rest = minor % unit;
  if (rest == 0) return 0;
  return (unit - rest) / 100;
}

/// Округлять ли эту операцию. Округляется только расход: доход, перевод и
/// вклад в цель округлять нечего, а скрытая трата не должна плодить второй
/// записи — по ней партнёр догадается о сюрпризе.
bool roundUpApplies(Transaction op, Rules rules) =>
    rules.roundUpStep > 0 &&
    rules.roundUpGoal.isNotEmpty &&
    op.kind == TxKind.expense &&
    !op.secret &&
    !op.hidden;

import 'dart:convert';
import 'dart:math';
import 'dart:typed_data';

import 'package:cryptography/cryptography.dart';

/// Шифрование снимков базы.
///
/// Правило, из которого всё следует: снимок шифрует ТЕЛЕФОН, а сервер хранит
/// непрозрачный кусок. Ключа у нас нет и быть не должно — это деньги пары, и
/// «мы не можем это прочитать» обязано быть правдой, а не обещанием.
///
/// Отсюда цена, о которой человеку говорят ДО первого снимка, а не после
/// потери: фраза восстановления — единственный способ открыть снимки на новом
/// телефоне. Потерял фразу и телефон разом — снимки мёртвые. Зато сервер,
/// который их держит, не откроет их ни по запросу, ни по ошибке.
///
/// Шифр — AES-GCM: он же проверяет целостность, поэтому подменённый кусок не
/// расшифруется, а не выдаст мусор за данные.
class SnapshotCrypto {
  static final _aes = AesGcm.with256bits();
  static final _pbkdf2 = Pbkdf2(
    macAlgorithm: Hmac.sha256(),
    // Сто тысяч кругов: фраза из шести слов сама по себе слабее случайного
    // ключа, и подбор должен стоить дорого.
    iterations: 100000,
    bits: 256,
  );

  /// Слова фразы восстановления.
  ///
  /// Русские, короткие и непохожие друг на друга: человек переписывает их
  /// рукой на бумагу, и «конституция» с «конституционный» в одном списке —
  /// прямая дорога к ошибке. Набор небольшой нарочно: шесть слов из ста
  /// двадцати восьми дают 42 бита, а вместе с солью и ста тысячами кругов
  /// перебор становится бессмысленным.
  static const words = <String>[
    'якорь', 'берег', 'ветер', 'гнездо', 'дорога', 'ель', 'жемчуг', 'звезда',
    'искра', 'камень', 'лодка', 'море', 'небо', 'озеро', 'поле', 'река',
    'соль', 'туман', 'утро', 'фонарь', 'холм', 'цветок', 'чайка', 'шторм',
    'щавель', 'эхо', 'юла', 'янтарь', 'арка', 'башня', 'волна', 'город',
    'дом', 'ежевика', 'жёлудь', 'заря', 'ива', 'ключ', 'луна', 'мост',
    'нить', 'облако', 'парус', 'роса', 'север', 'тропа', 'улей', 'фара',
    'хлеб', 'цепь', 'час', 'шалаш', 'щит', 'эра', 'юг', 'ясень',
    'астра', 'брод', 'ворон', 'гром', 'дуб', 'ёлка', 'жар', 'зерно',
    'иней', 'корень', 'лист', 'мята', 'нора', 'орех', 'песок', 'рябина',
    'сад', 'тис', 'угол', 'фрегат', 'хвоя', 'цикада', 'чаща', 'шишка',
    'щука', 'этаж', 'юрта', 'ягода', 'алмаз', 'берёза', 'вода', 'гора',
    'долина', 'ёж', 'журавль', 'закат', 'изба', 'колос', 'лён', 'маяк',
    'невод', 'омут', 'прилив', 'радуга', 'снег', 'тень', 'ущелье', 'фьорд',
    'хутор', 'цапля', 'челн', 'шёпот', 'щегол', 'эстуарий', 'юноша', 'ярус',
    'арбуз', 'бор', 'вереск', 'галька', 'дюна', 'ёрш', 'заводь', 'ирис',
    'клён', 'ландыш', 'миндаль', 'ночь', 'осока', 'пруд', 'рассвет', 'стебель',
  ];

  /// Сколько слов в фразе.
  static const phraseLength = 6;

  /// Новая фраза восстановления.
  static List<String> newPhrase() {
    final rnd = Random.secure();
    return [for (var i = 0; i < phraseLength; i++) words[rnd.nextInt(words.length)]];
  }

  /// Новая соль. Хранится РЯДОМ со снимками на сервере: без фразы она
  /// бесполезна, а без неё фразу не превратить обратно в ключ.
  static String newSalt() {
    final rnd = Random.secure();
    return base64Url.encode([for (var i = 0; i < 16; i++) rnd.nextInt(256)]);
  }

  /// Ключ из фразы и соли.
  static Future<SecretKey> keyOf(List<String> phrase, String salt) =>
      _pbkdf2.deriveKeyFromPassword(
        password: phrase.map((w) => w.trim().toLowerCase()).join(' '),
        nonce: base64Url.decode(salt),
      );

  /// Зашифровать снимок. На выходе — одна строка base64: `nonce|тело|метка`.
  static Future<String> seal(SecretKey key, String json) async {
    final box = await _aes.encrypt(utf8.encode(json), secretKey: key);
    return base64.encode(box.concatenation());
  }

  /// Расшифровать. Пусто — фраза не та или кусок подменён: AES-GCM проверяет
  /// целостность сам, и выдать мусор за данные он не может.
  static Future<String> open(SecretKey key, String blob) async {
    try {
      final raw = base64.decode(blob);
      final box = SecretBox.fromConcatenation(
        raw,
        nonceLength: 12,
        macLength: 16,
      );
      final clear = await _aes.decrypt(box, secretKey: key);
      return utf8.decode(Uint8List.fromList(clear));
    } catch (_) {
      return '';
    }
  }
}

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';

/// Тактильные отклики приложения.
///
/// Одна дверь на все вибрации: какой отклик какому событию положен, решается
/// здесь, а не в пятнадцати экранах. Иначе «записал трату» и «не тот код»
/// однажды начнут отвечать одинаково, и палец перестанет их различать.
///
/// Правила, из которых собран этот список:
///
/// * отклик отвечает на ДЕЙСТВИЕ человека, а не на движение экрана. Вибрация
///   на прокрутку, на смену вкладки и на каждый кадр анимации — способ
///   разрядить батарею и добиться, чтобы отклики выключили совсем;
/// * сила говорит о последствиях. Выбор — едва заметный щелчок, сделанное —
///   мягкий толчок, отказ и удаление — отчётливый;
/// * отклика НЕ ждут (`await` тут не нужен): ответ платформы занимает кадр, и
///   ожидание откладывает само действие. Так уже вышло с замком — открытие
///   запаздывало на щелчок.
class Tap {
  const Tap._();

  static const _channel = MethodChannel('money/haptics');

  /// Играть свой эффект или просить систему.
  ///
  /// Системного щелчка мало: `HapticFeedback` шлёт `CLOCK_TICK` и
  /// `VIRTUAL_KEY`, а прошивки — Xiaomi в первую очередь — глушат их вместе с
  /// виброоткликом касаний, и человек не чувствует НИЧЕГО (17.09.2026).
  /// Поэтому на Android мы играем эффект своим мотором, а системный отклик
  /// остаётся запасным путём: он работает на iOS и там, где канала нет
  /// (тесты, десктоп).
  static bool _own = defaultTargetPlatform == TargetPlatform.android;

  static void _buzz(String kind, VoidCallback fallback) {
    if (!_own) {
      fallback();
      return;
    }
    _channel.invokeMethod<bool>('buzz', {'kind': kind}).then((ok) {
      // Мотора нет вовсе — больше не тревожим канал и отдаём системе.
      if (ok != true) {
        _own = false;
        fallback();
      }
    }).catchError((_) {
      _own = false;
      fallback();
      return null;
    });
  }

  /// Выбор: пилюля, барабан, ячейка списка. Самый тихий отклик.
  static void pick() => _buzz('pick', HapticFeedback.selectionClick);

  /// Сделано: трата записана, список подтверждён, замок открылся.
  static void done() => _buzz('done', HapticFeedback.lightImpact);

  /// Отказ и опасное: неверный код, удаление, отклонённое списание.
  static void warn() => _buzz('warn', HapticFeedback.mediumImpact);

  /// Событие, которого человек ждал месяцами: цель собрана, долг закрыт.
  /// Редкий отклик — оттого и заметный.
  static void cheer() => _buzz('cheer', HapticFeedback.heavyImpact);

  /// Вернуть выбор канала в исходное состояние. Нужно тестам: одна неудача
  /// канала иначе выключала бы свой мотор для всего прогона.
  @visibleForTesting
  static void resetForTest() {
    _own = defaultTargetPlatform == TargetPlatform.android;
  }
}
